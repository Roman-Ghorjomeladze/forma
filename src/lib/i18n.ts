const DICTS: Record<Lang, Dict> = { en: EN, ka: KA };

function interpolate(s: string, vars?: Vars): string {
  if (!vars) return s;
  let out = s;
  for (const k of Object.keys(vars)) out = out.split(`{${k}}`).join(String(vars[k]));
  return out;
}

export function translate(lang: Lang, key: string, vars?: Vars): string {
  const s = DICTS[lang]?.[key] ?? EN[key] ?? key;
  return interpolate(s, vars);
}

/** Plain (non-hook) translate using the current language — for modules outside React. */
export function tGlobal(key: string, vars?: Vars): string {
  return translate(getLang(), key, vars);
}

/** Hook form: re-renders the calling component when the language preference changes. */
export function useT(): (key: string, vars?: Vars) => string {
  const [prefs] = usePrefs();
  const lang = prefs.language;
  return (key: string, vars?: Vars) => translate(lang, key, vars);
}

export function useLang(): Lang {
  const [prefs] = usePrefs();
  return prefs.language;
}
